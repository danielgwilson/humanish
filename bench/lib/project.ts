// Builds the throwaway project a benchmark runs in: the two Taskly builds, the persona and one
// generated study per brain and arm. With local storage, each build's app.js comes from its
// `-local` directory, which keeps tasks in localStorage across a page reload; index.html is shared. The builds are served from `build-a` and `build-b`, and study
// ids use the same letters, so no file or id the participant's desktop or the analyst receives says
// which arm it is. The manifest beside the project keeps the mapping. checkStudy runs the CLI's
// dry run of each study, which reads back the mission the CLI under test would send.

import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import type { Arm, Storage } from "../taskly/answer-key.js";
import type { Mission } from "../taskly/missions.js";
import { readRunBundle, type RunBundle } from "./bundle.js";
import { numberField, objectField, runCli, stringField } from "./humanish-cli.js";
import type { Brain } from "./plan.js";

export const REPO_ROOT = path.resolve(import.meta.dirname, "..", "..");

/** The benchmark's persona, which every published result before 2026-10-24 used. */
export const DEFAULT_PERSONA_FILE = path.join(REPO_ROOT, "humanish", "personas", "synthetic-new-user.yaml");
const BUILD_DIR: Record<Arm, string> = { planted: "build-a", clean: "build-b" };

/** The bench directory whose app.js a build serves. */
function appDir(arm: Arm, storage: Storage): string {
  return `bench/taskly-${arm}${storage === "local" ? "-local" : ""}`;
}

const CHECK_TIMEOUT_MS = 5 * 60_000;

/** The participant's session limit, matching humanish/studies/detect-taskly-*.yaml. */
export const SESSION_TIMEOUT_MS = 600_000;

export function sha256(bytes: string | Buffer): string {
  return createHash("sha256").update(bytes).digest("hex");
}

export interface FixtureDigests {
  plantedAppJs: string;
  cleanAppJs: string;
  indexHtml: string;
  persona: string;
}

/** The persona id a persona file declares, which the generated studies name. */
export function personaId(personaFile: string): string {
  const id = /^id:\s*([a-z0-9][a-z0-9-]*)\s*$/m.exec(readFileSync(personaFile, "utf8"))?.[1];
  if (id === undefined) throw new Error(`${personaFile} declares no persona id.`);
  return id;
}

export function fixtureDigests(
  personaFile: string = DEFAULT_PERSONA_FILE,
  storage: Storage = "memory",
): FixtureDigests {
  const read = (relative: string): Buffer => readFileSync(path.join(REPO_ROOT, relative));
  return {
    plantedAppJs: sha256(read(`${appDir("planted", storage)}/app.js`)),
    cleanAppJs: sha256(read(`${appDir("clean", storage)}/app.js`)),
    indexHtml: sha256(read("bench/taskly-planted/index.html")),
    persona: sha256(readFileSync(personaFile)),
  };
}

export function studyId(brain: Brain, arm: Arm): string {
  return `bench-taskly-${BUILD_DIR[arm].slice(-1)}-${brain.id}`;
}

/** The study manifest for one brain and arm. JSON-quoted scalars are valid YAML. */
export function studyYaml(
  brain: Brain,
  arm: Arm,
  mission: Mission,
  participantCapUsd: number,
  persona = "synthetic-new-user",
  pointer?: "glide" | "jump",
): string {
  const id = studyId(brain, arm);
  const actor = Object.entries(brain.actor)
    .map(([key, value]) => `  ${key}: ${JSON.stringify(value)}`)
    .join("\n");
  const caps = brain.priced ? `caps:\n  maxUsd: ${participantCapUsd}\n` : "";
  return `schema: humanish.study.v3
id: ${id}
title: ${JSON.stringify(`Taskly benchmark, build ${BUILD_DIR[arm].slice(-1)}, ${brain.id}`)}
description: "Generated by bench/run.ts for one benchmark invocation."
route: computer-use
mode: live
subject:
  source: local-tree
  serve:
    start: python3 -m http.server 8000 --directory ${BUILD_DIR[arm]}
    url: http://127.0.0.1:8000/
actor:
${actor}
  persona: ${persona}
${mission.text === null ? "" : `  mission: ${JSON.stringify(mission.text)}\n`}${caps}execution:
  target: e2b-desktop
${pointer === undefined ? "" : `  pointer: ${pointer}\n`}  timeoutMs: ${SESSION_TIMEOUT_MS}
review:
  analysis: false
policies:
  allowPrivateRepoAccess: false
  allowProviderCredentials: false
  allowPaymentCredentials: false
  allowGitHubMutation: false
`;
}

/** Write the project: both builds with the chosen storage, the persona and a study per brain and arm. */
export function writeProject(
  projectDir: string,
  brains: readonly Brain[],
  mission: Mission,
  participantCapUsd: number,
  personaFile: string = DEFAULT_PERSONA_FILE,
  storage: Storage = "memory",
  pointer?: "glide" | "jump",
): void {
  const persona = personaId(personaFile);
  mkdirSync(path.join(projectDir, "humanish", "studies"), { recursive: true });
  mkdirSync(path.join(projectDir, "humanish", "personas"), { recursive: true });
  for (const arm of ["planted", "clean"] as const) {
    const served = path.join(projectDir, BUILD_DIR[arm]);
    cpSync(path.join(REPO_ROOT, appDir(arm, "memory")), served, { recursive: true });
    cpSync(path.join(REPO_ROOT, appDir(arm, storage), "app.js"), path.join(served, "app.js"));
  }
  cpSync(personaFile, path.join(projectDir, "humanish", "personas", `${persona}.yaml`));
  for (const brain of brains) {
    for (const arm of ["planted", "clean"] as const) {
      writeFileSync(
        path.join(projectDir, "humanish", "studies", `${studyId(brain, arm)}.yaml`),
        studyYaml(brain, arm, mission, participantCapUsd, persona, pointer),
      );
    }
  }
}

export type StudyCheck =
  /** `refused`: the CLI refused the study. `no_bundle`: it answered ok but left no readable dry-run bundle. */
  | { ok: false; reason: "refused" | "no_bundle" }
  | {
      ok: true;
      /** The mission every participant of the dry run recorded, null when they differ or record none. */
      mission: string | null;
      worstCaseSandboxMinutes: number | null;
    };

/**
 * The CLI's own dry run of one generated study. It checks the study, and its bundle records the
 * mission the CLI under test would send, which for a study with no mission line is its built-in one.
 */
export async function checkStudy(
  target: { cliPath: string; projectDir: string; logFile: string; studyId: string },
  cli: typeof runCli = runCli,
): Promise<StudyCheck> {
  const check = await cli(
    target.cliPath,
    ["run", target.studyId, "--cwd", target.projectDir, "--dry-run", "--no-open", "--detach", "--json"],
    { logFile: target.logFile, timeoutMs: CHECK_TIMEOUT_MS },
  );
  const runId = stringField(check.json, "runId");
  if (check.code !== 0 || check.json?.ok !== true) return { ok: false, reason: "refused" };
  let bundle: RunBundle | null = null;
  try {
    if (runId !== null) bundle = readRunBundle(target.projectDir, runId);
  } catch {
    // An unreadable bundle is reported as a missing one.
  }
  if (bundle === null) return { ok: false, reason: "no_bundle" };
  const missions = new Set(bundle.streams.map((stream) => stream.assignment?.mission ?? null));
  const [only] = missions;
  return {
    ok: true,
    mission: missions.size === 1 ? (only ?? null) : null,
    worstCaseSandboxMinutes: numberField(objectField(check.json, "plan"), "worstCaseSandboxMinutes"),
  };
}
